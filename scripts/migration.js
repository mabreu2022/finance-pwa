const Firebird = require('node-firebird');
const path = require('path');

const dbPath = path.join(__dirname, '..', 'public', 'database', 'BANCOFINANCAS.FDB');

const options = {
  database: dbPath,
  user: 'SYSDBA',
  password: 'masterkey'
};

async function run() {
  console.log('🚀 Iniciando migração para suporte a múltiplas contas bancárias...\n');
  
  let db;
  try {
    db = await new Promise((resolve, reject) => {
      Firebird.attach(options, (err, database) => {
        if (err) reject(err);
        else resolve(database);
      });
    });

    const query = (sql, params = []) => {
      return new Promise((resolve, reject) => {
        db.query(sql, params, (err, result) => {
          if (err) reject(err);
          else resolve(result || []);
        });
      });
    };

    const execute = (sql, params = []) => {
      return new Promise((resolve, reject) => {
        db.query(sql, params, (err, result) => {
          if (err) reject(err);
          else resolve(result);
        });
      });
    };

    // 1. Verificar se a tabela CONTAS_BANCARIAS já existe
    const tableExists = await query(
      "SELECT RDB$RELATION_NAME FROM RDB$RELATIONS WHERE RDB$SYSTEM_FLAG = 0 AND RDB$RELATION_NAME = 'CONTAS_BANCARIAS'"
    );

    if (tableExists.length === 0) {
      console.log('  📊 Criando tabela CONTAS_BANCARIAS...');
      await execute(`
        CREATE TABLE CONTAS_BANCARIAS (
          ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          TENANT_ID INTEGER NOT NULL,
          NOME VARCHAR(100) NOT NULL,
          TIPO VARCHAR(50) NOT NULL,
          SALDO_INICIAL DECIMAL(10,2) DEFAULT 0,
          SALDO_ATUAL DECIMAL(10,2) DEFAULT 0,
          ATIVO VARCHAR(1) DEFAULT 'S',
          DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID)
        )
      `);
      console.log('  ✅ Tabela CONTAS_BANCARIAS criada com sucesso.');
    } else {
      console.log('  ℹ️ Tabela CONTAS_BANCARIAS já existe.');
    }

    // 2. Verificar se a coluna CONTA_BANCARIA_ID já existe na tabela CONTAS
    const columnExists = await query(
      "SELECT RDB$FIELD_NAME FROM RDB$RELATION_FIELDS WHERE TRIM(RDB$RELATION_NAME) = 'CONTAS' AND TRIM(RDB$FIELD_NAME) = 'CONTA_BANCARIA_ID'"
    );

    if (columnExists.length === 0) {
      console.log('  📊 Adicionando coluna CONTA_BANCARIA_ID à tabela CONTAS...');
      await execute('ALTER TABLE CONTAS ADD CONTA_BANCARIA_ID INTEGER');
      console.log('  ✅ Coluna CONTA_BANCARIA_ID adicionada com sucesso.');
    } else {
      console.log('  ℹ️ Coluna CONTA_BANCARIA_ID já existe na tabela CONTAS.');
    }

    // 3. Garantir conta bancária padrão ("Conta Principal") para todos os Tenants
    console.log('  👥 Verificando inquilinos (Tenants)...');
    const tenants = await query('SELECT ID, NOME FROM TENANTS');
    
    for (const tenant of tenants) {
      const tenantId = tenant.ID;
      const tenantNome = tenant.NOME.trim();
      
      // Verificar se já existe alguma conta bancária para este tenant
      const bankAccounts = await query('SELECT ID FROM CONTAS_BANCARIAS WHERE TENANT_ID = ?', [tenantId]);
      let defaultAccountId;

      if (bankAccounts.length === 0) {
        console.log(`    Creating default account for tenant "${tenantNome}" (ID: ${tenantId})...`);
        const insertResult = await execute(
          `INSERT INTO CONTAS_BANCARIAS (TENANT_ID, NOME, TIPO, SALDO_INICIAL, SALDO_ATUAL, ATIVO)
           VALUES (?, 'Conta Principal', 'CORRENTE', 0, 0, 'S')
           RETURNING ID`,
           [tenantId]
        );
        defaultAccountId = insertResult.ID || insertResult[0]?.ID;
        console.log(`    ✅ Conta Principal criada com ID ${defaultAccountId}.`);
      } else {
        defaultAccountId = bankAccounts[0].ID;
        console.log(`    ℹ️ Tenant "${tenantNome}" já possui conta bancária (ID: ${defaultAccountId}).`);
      }

      // Associar todas as CONTAS sem CONTA_BANCARIA_ID para a conta padrão do Tenant
      const unassignedContas = await query(
        'SELECT COUNT(*) AS CNT FROM CONTAS WHERE TENANT_ID = ? AND CONTA_BANCARIA_ID IS NULL',
        [tenantId]
      );
      
      const count = unassignedContas[0].CNT || 0;
      if (count > 0) {
        console.log(`    Updating ${count} transactions to point to default account ID ${defaultAccountId}...`);
        await execute(
          'UPDATE CONTAS SET CONTA_BANCARIA_ID = ? WHERE TENANT_ID = ? AND CONTA_BANCARIA_ID IS NULL',
          [defaultAccountId, tenantId]
        );
        console.log('    ✅ Transações atualizadas.');
      }
    }

    // 4. Criar índice na FK
    const indexExists = await query(
      "SELECT RDB$INDEX_NAME FROM RDB$INDICES WHERE TRIM(RDB$RELATION_NAME) = 'CONTAS' AND TRIM(RDB$INDEX_NAME) = 'IX_CONTAS_CONTA_BANCARIA'"
    );
    if (indexExists.length === 0) {
      console.log('  🔍 Criando índice IX_CONTAS_CONTA_BANCARIA...');
      await execute('CREATE INDEX IX_CONTAS_CONTA_BANCARIA ON CONTAS(CONTA_BANCARIA_ID)');
      console.log('  ✅ Índice criado.');
    }

    // 5. Adicionar a constraint de chave estrangeira
    const constraintExists = await query(
      `SELECT RDB$CONSTRAINT_NAME FROM RDB$RELATION_CONSTRAINTS 
       WHERE TRIM(RDB$RELATION_NAME) = 'CONTAS' AND TRIM(RDB$CONSTRAINT_NAME) = 'FK_CONTAS_CONTA_BANCARIA'`
    );

    if (constraintExists.length === 0) {
      console.log('  🔒 Adicionando chave estrangeira FK_CONTAS_CONTA_BANCARIA...');
      await execute(`
        ALTER TABLE CONTAS ADD CONSTRAINT FK_CONTAS_CONTA_BANCARIA 
        FOREIGN KEY (CONTA_BANCARIA_ID) REFERENCES CONTAS_BANCARIAS(ID)
      `);
      console.log('  ✅ Chave estrangeira adicionada com sucesso.');
    } else {
      console.log('  ℹ️ Chave estrangeira FK_CONTAS_CONTA_BANCARIA já existe.');
    }

    // 6. Recalcular os saldos atuais de todas as contas bancárias baseados nas transações pagas/recebidas
    console.log('\n📊 Recalculando saldos atuais de todas as contas bancárias...');
    const accounts = await query('SELECT ID, TENANT_ID, NOME FROM CONTAS_BANCARIAS');
    for (const acc of accounts) {
      const id = acc.ID;
      const tenantId = acc.TENANT_ID;
      const nome = acc.NOME.trim();

      const resReceber = await query(
        "SELECT SUM(VALOR) AS TOTAL FROM CONTAS WHERE CONTA_BANCARIA_ID = ? AND STATUS = 'RECEBIDO'",
        [id]
      );
      const resPagar = await query(
        "SELECT SUM(VALOR) AS TOTAL FROM CONTAS WHERE CONTA_BANCARIA_ID = ? AND STATUS = 'PAGO'",
        [id]
      );
      
      const totalReceber = Number(resReceber[0]?.TOTAL || 0);
      const totalPagar = Number(resPagar[0]?.TOTAL || 0);
      
      await execute(
        "UPDATE CONTAS_BANCARIAS SET SALDO_ATUAL = SALDO_INICIAL + ? - ? WHERE ID = ? AND TENANT_ID = ?",
        [totalReceber, totalPagar, id, tenantId]
      );
      
      const updatedAcc = await query('SELECT SALDO_ATUAL FROM CONTAS_BANCARIAS WHERE ID = ?', [id]);
      console.log(`    - Conta "${nome}" (ID: ${id}): Saldo atualizado para R$ ${updatedAcc[0].SALDO_ATUAL.toFixed(2)}`);
    }

    console.log('\n🎉 MIGRAÇÃO CONCLUÍDA COM SUCESSO!');
  } catch (error) {
    console.error('\n❌ Erro durante a migração:', error.message);
    console.error(error.stack);
  } finally {
    if (db) {
      db.detach();
    }
  }
}

run();
