const Firebird = require('node-firebird');
const path = require('path');

const dbPath = path.join(__dirname, '..', 'public', 'database', 'BANCOFINANCAS.FDB');

async function initDatabase() {
  console.log('🚀 Iniciando criação do banco de dados...\n');
  
  try {
    const options = {
      database: dbPath,
      user: 'SYSDBA',
      password: 'masterkey',
      role: null,
      pageSize: 4096
    };
    const db = await new Promise((resolve, reject) => {
      Firebird.attach(options, (err, database) => {
        if (err) reject(err);
        else resolve(database);
      });
    });
    console.log('✅ Banco de dados conectado:', dbPath);

    const query = (sql, params = []) => {
      return new Promise((resolve, reject) => {
        db.query(sql, params, (err, result) => {
          if (err) reject(err);
          else resolve(result);
        });
      });
    };

    // Criar tabela PLANOS
    console.log('\n📊 Criando tabelas...');
    await query(`
      CREATE TABLE PLANOS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NOME VARCHAR(100) NOT NULL,
        DESCRICAO BLOB SUB_TYPE TEXT,
        VALOR_MENSAL DECIMAL(10,2) DEFAULT 0,
        LIMITE_USUARIOS INTEGER DEFAULT 1,
        LIMITE_CONTAS INTEGER,
        FEATURES BLOB SUB_TYPE TEXT,
        ATIVO VARCHAR(1) DEFAULT 'S',
        DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);
    console.log('  ✅ PLANOS');

    // Criar tabela TENANTS
    await query(`
      CREATE TABLE TENANTS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NOME VARCHAR(100) NOT NULL,
        CNPJ VARCHAR(20),
        NOME_FANTASIA VARCHAR(100),
        EMAIL_ADMIN VARCHAR(100),
        TELEFONE VARCHAR(20),
        ENDERECO BLOB SUB_TYPE TEXT,
        DOMINIO VARCHAR(100) UNIQUE,
        STATUS VARCHAR(20) DEFAULT 'TRIAL',
        PLANO_ID INTEGER,
        LIMITE_USUARIOS INTEGER DEFAULT 1,
        DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        DATA_EXPIRACAO DATE,
        DATA_ULTIMA_FATURA DATE,
        VALOR_MENSAL DECIMAL(10,2) DEFAULT 0,
        FOREIGN KEY (PLANO_ID) REFERENCES PLANOS(ID)
      )
    `);
    console.log('  ✅ TENANTS');

    // Criar tabela USUARIOS
    await query(`
      CREATE TABLE USUARIOS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TENANT_ID INTEGER NOT NULL,
        NOME VARCHAR(100) NOT NULL,
        EMAIL VARCHAR(100) NOT NULL,
        SENHA VARCHAR(255) NOT NULL,
        ROLE VARCHAR(20) DEFAULT 'USER',
        STATUS VARCHAR(20) DEFAULT 'ATIVO',
        FONE VARCHAR(20),
        ULTIMO_ACESSO TIMESTAMP,
        TENTATIVAS_LOGIN INTEGER DEFAULT 0,
        BLOQUEADO_AT TIMESTAMP,
        DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(TENANT_ID, EMAIL),
        FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID)
      )
    `);
    console.log('  ✅ USUARIOS');

    // Criar tabela CONTAS
    await query(`
      CREATE TABLE CONTAS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TENANT_ID INTEGER NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        DESCRICAO VARCHAR(255) NOT NULL,
        VALOR DECIMAL(10,2) NOT NULL,
        DATA_VENCIMENTO DATE NOT NULL,
        DATA_PAGAMENTO DATE,
        CATEGORIA VARCHAR(50) NOT NULL,
        STATUS VARCHAR(20) DEFAULT 'PENDENTE',
        TIPO VARCHAR(10) NOT NULL,
        OBSERVACOES BLOB SUB_TYPE TEXT,
        PARCELA_ATUAL INTEGER,
        PARCELA_TOTAL INTEGER,
        CONTA_PAI_ID INTEGER,
        DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID),
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
        FOREIGN KEY (CONTA_PAI_ID) REFERENCES CONTAS(ID)
      )
    `);
    console.log('  ✅ CONTAS');

    // Criar tabela AGENDAMENTOS
    await query(`
      CREATE TABLE AGENDAMENTOS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TENANT_ID INTEGER NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        DESCRICAO VARCHAR(255) NOT NULL,
        VALOR DECIMAL(10,2) NOT NULL,
        DIA_FIXO INTEGER NOT NULL,
        CATEGORIA VARCHAR(50) NOT NULL,
        TIPO VARCHAR(10) NOT NULL,
        RECORRENTE VARCHAR(1) DEFAULT 'N',
        ATIVO VARCHAR(1) DEFAULT 'S',
        ULTIMA_EXECUCAO DATE,
        PROXIMA_EXECUCAO DATE,
        DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID),
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
      )
    `);
    console.log('  ✅ AGENDAMENTOS');

    // Criar tabela ASSINATURAS
    await query(`
      CREATE TABLE ASSINATURAS (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TENANT_ID INTEGER NOT NULL,
        PLANO_ID INTEGER,
        STATUS VARCHAR(20) DEFAULT 'ATIVA',
        DATA_INICIO DATE NOT NULL,
        DATA_FIM DATE,
        VALOR_PAGO DECIMAL(10,2),
        FORMA_PAGAMENTO VARCHAR(50),
        DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID),
        FOREIGN KEY (PLANO_ID) REFERENCES PLANOS(ID)
      )
    `);
    console.log('  ✅ ASSINATURAS');

    // Criar tabela LOGS_AUDITORIA
    await query(`
      CREATE TABLE LOGS_AUDITORIA (
        ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TENANT_ID INTEGER,
        USUARIO_ID INTEGER,
        ACAO VARCHAR(50) NOT NULL,
        TABELA_AFETADA VARCHAR(50),
        REGISTRO_ID INTEGER,
        DETALHES BLOB SUB_TYPE TEXT,
        IP_ACESSO VARCHAR(45),
        DATA_ACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (TENANT_ID) REFERENCES TENANTS(ID),
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID)
      )
    `);
    console.log('  ✅ LOGS_AUDITORIA');

    // Criar índices
    console.log('\n🔍 Criando índices...');
    await query('CREATE INDEX IX_CONTAS_TENANT ON CONTAS(TENANT_ID)');
    await query('CREATE INDEX IX_CONTAS_USUARIO ON CONTAS(USUARIO_ID)');
    await query('CREATE INDEX IX_CONTAS_STATUS ON CONTAS(STATUS)');
    await query('CREATE INDEX IX_USUARIOS_TENANT ON USUARIOS(TENANT_ID)');
    await query('CREATE INDEX IX_AGENDAMENTOS_TENANT ON AGENDAMENTOS(TENANT_ID)');
    await query('CREATE INDEX IX_TENANTS_DOMINIO ON TENANTS(DOMINIO)');
    console.log('  ✅ Índices criados');

    // Verificar se já tem dados
    const planosResult = await query('SELECT COUNT(*) AS CNT FROM PLANOS');
    const planosCount = planosResult[0].CNT;
    
    if (planosCount === 0) {
      console.log('\n📝 Inserindo dados iniciais...');

      // Inserir Planos
      await query(`
        INSERT INTO PLANOS (NOME, DESCRICAO, VALOR_MENSAL, LIMITE_USUARIOS, LIMITE_CONTAS, FEATURES)
        VALUES (?, ?, ?, ?, ?, ?)
      `, ['FREE', 'Plano gratuito para testes', 0, 1, 100, 'DASHBOARD,CONTAS_PAGAR,CONTAS_RECEBER,RELATORIOS_BASICOS']);
      
      await query(`
        INSERT INTO PLANOS (NOME, DESCRICAO, VALOR_MENSAL, LIMITE_USUARIOS, LIMITE_CONTAS, FEATURES)
        VALUES (?, ?, ?, ?, ?, ?)
      `, ['PROFISSIONAL', 'Plano para profissionais liberais', 49.90, 5, null, 'DASHBOARD,CONTAS_PAGAR,CONTAS_RECEBER,RELATORIOS_AVANCADOS,AGENDAMENTOS,EXPORT_PDF,USUARIOS']);
      
      await query(`
        INSERT INTO PLANOS (NOME, DESCRICAO, VALOR_MENSAL, LIMITE_USUARIOS, LIMITE_CONTAS, FEATURES)
        VALUES (?, ?, ?, ?, ?, ?)
      `, ['EMPRESARIAL', 'Plano para pequenas empresas', 149.90, null, null, 'DASHBOARD,CONTAS_PAGAR,CONTAS_RECEBER,RELATORIOS_AVANCADOS,AGENDAMENTOS,EXPORT_PDF,USUARIOS,API_ACCESS,PRIORIDADE_SUPORTE']);
      
      console.log('  ✅ 3 Planos inseridos');

      // Inserir Tenant Master
      await query(`
        INSERT INTO TENANTS (NOME, CNPJ, NOME_FANTASIA, EMAIL_ADMIN, TELEFONE, STATUS, PLANO_ID)
        VALUES (?, ?, ?, ?, ?, ?, ?)
      `, ['Master Admin', '00.000.000/0001-00', 'Connect Finance', 'admin@master', '11999999999', 'ATIVO', 3]);
      console.log('  ✅ Tenant Master criado');

      // Inserir Super Admin (senha: admin123)
      await query(`
        INSERT INTO USUARIOS (TENANT_ID, NOME, EMAIL, SENHA, ROLE, STATUS)
        VALUES (?, ?, ?, ?, ?, ?)
      `, [1, 'Super Admin', 'admin@master', 'YWRtaW4xMjM=', 'ADMIN', 'ATIVO']);
      console.log('  ✅ Super Admin criado');

      // Inserir Admin Demo (senha: demo123)
      await query(`
        INSERT INTO USUARIOS (TENANT_ID, NOME, EMAIL, SENHA, ROLE, STATUS)
        VALUES (?, ?, ?, ?, ?, ?)
      `, [1, 'Admin Demo', 'admin@demo', 'ZGVtbzEyMw==', 'ADMIN', 'ATIVO']);
      console.log('  ✅ Admin Demo criado');

      // Inserir Assinatura Master
      await query(`
        INSERT INTO ASSINATURAS (TENANT_ID, PLANO_ID, STATUS, DATA_INICIO, VALOR_PAGO, FORMA_PAGAMENTO)
        VALUES (?, ?, ?, CURRENT_DATE, ?, ?)
      `, [1, 3, 'ATIVA', 0, 'BOLETO']);
      console.log('  ✅ Assinatura Master criada');
    } else {
      console.log('\nℹ️  Dados iniciais já existem, pulando...');
    }

    db.detach();
    
    console.log('\n🎉 BANCO DE DADOS CRIADO COM SUCESSO!');
    console.log('\n📌 Credenciais de acesso:');
    console.log('   Super Admin: admin@master / admin123');
    console.log('   Admin Demo:  admin@demo / demo123');
    console.log('\n💾 Arquivo:', dbPath);

  } catch (error) {
    console.error('❌ Erro:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

initDatabase();
